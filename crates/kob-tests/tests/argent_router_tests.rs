/// Router sources: the committed generated `.sil`, optionally ablated. Every ablation edits ONE
/// entry of the generated source (the region from `entry <name>(` to the next entry) and asserts
/// that each edited line occurs exactly once there, so a change of the generated router cannot
/// silently make an ablation a no-op.
#[derive(Clone, Copy, PartialEq, Debug)]
enum Router {
    Shipped,
    /// KasToToken.buy without the positional rule: the payer change index is a keeper-chosen entry
    /// argument and the delivery position is not tied to the intent.
    NaiveBuy,
    /// KasToToken.buy2 without the positional rule (same edit as `NaiveBuy`).
    NaiveBuy2,
    /// KasToToken.buy2 bounds the price per ask instead of over the sweep.
    BuyPerLegPrice,
    /// TokenToKas.sell2 bounds `max_sell` per bid instead of over the sweep.
    SellPerLegBound,
    /// TokenSwap.swap2 bounds `max_sell_a` per bid instead of over the sweep.
    SwapPerLegBound,
}
/// Text of `entry <name>(` up to (not including) the next `entry ` line.
fn entry_range(s: &str, name: &str) -> (usize, usize) {
    let head = format!("    entry {name}(\n");
    assert_eq!(s.matches(&head).count(), 1, "generated router has no unique entry {name}");
    let start = s.find(&head).unwrap();
    let end = s[start + 1..].find("\n    entry ").map(|i| start + 1 + i).unwrap_or(s.len());
    (start, end)
}
/// Apply `edits` (needle, replacement) inside entry `name`; each needle must occur exactly once.
fn ablate(s: &str, name: &str, edits: &[(&str, String)]) -> String {
    let (a, b) = entry_range(s, name);
    let mut region = s[a..b].to_string();
    for (needle, with) in edits {
        assert_eq!(region.matches(needle).count(), 1, "generated router changed: cannot ablate `{needle}` in {name}");
        region = region.replace(needle, with);
    }
    format!("{}{}{}", &s[..a], region, &s[b..])
}
/// The positional-rule ablation of a KasToToken entry: the change index is an entry argument.
fn naive_positional(s: &str, entry: &str, first_arg: &str, last_arg: &str) -> String {
    let sig = format!("{first_arg}\n{last_arg}");
    let change = "require(tx.outputs[me].scriptPubKey == byte[](new ScriptPubKeyP2PK(payer)));";
    let value = "require(tx.outputs[me].value + pay + max_extra >= tx.inputs[this.activeInputIndex].value);";
    let deliver = "require(OpCovOutputIdx(token_covid, 1) == me + 1);";
    ablate(
        s,
        entry,
        &[
            (&sig, format!("{first_arg}\n        int change_out,\n{last_arg}")),
            (change, change.replace("outputs[me]", "outputs[change_out]")),
            (value, value.replace("outputs[me]", "outputs[change_out]")),
            (deliver, "require(OpCovOutputIdx(token_covid, 1) > 0);".to_string()),
            // the intent-last half of the positional rule goes with it
            ("require(tx.inputs.length == me + 1);", String::new()),
        ],
    )
}
fn router_src(name: &str, r: Router) -> String {
    let s = src(name).replace("\r\n", "\n");
    match r {
        Router::Shipped => s,
        Router::NaiveBuy => {
            assert_eq!(name, "KasToToken_buy");
            naive_positional(&s, "buy", "        byte[32] ask1_covid,", "        int gen__kob_orders__kob_ask_prefix_len,")
        }
        Router::NaiveBuy2 => {
            assert_eq!(name, "KasToToken_buy2");
            naive_positional(&s, "buy2", "        byte[32] ask2_covid,", "        int gen__kob_orders__kob_ask_prefix_len,")
        }
        Router::BuyPerLegPrice => {
            assert_eq!(name, "KasToToken_buy2");
            ablate(&s, "buy2", &[("require(pay <= max_pay);", "require(pay1 <= max_pay);\n        require(pay2 <= max_pay);".into())])
        }
        Router::SellPerLegBound => {
            assert_eq!(name, "TokenToKas_sell2");
            ablate(&s, "sell2", &[("require(sold <= max_sell);", "require(n1 <= max_sell);\n        require(n2 <= max_sell);".into())])
        }
        Router::SwapPerLegBound => {
            assert_eq!(name, "TokenSwap_swap2");
            // the sum of the base units sold into the two bids, bounded per bid instead
            ablate(
                &s,
                "swap2",
                &[(
                    "require(n_a1 + n_a2 <= max_sell_a);",
                    "require(n_a1 <= max_sell_a);\n        require(n_a2 <= max_sell_a);".into(),
                )],
            )
        }
    }
}
fn compile_router(name: &str, r: Router, args: &[ArtifactValue]) -> SilAbiArtifact {
    compile_contract(&router_src(name, r), args, CompileOptions::default()).unwrap_or_else(|e| panic!("compile {name}: {e:?}"))
}
