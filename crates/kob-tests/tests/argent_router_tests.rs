/// The production intent builders (`kob_protocol::router`, `build::intent`) embed exactly the router this harness
/// compiles from the committed generated sources: every actor's template hash and every instance's redeem script
/// (state encoding included) match, so the covenant cases above hold for the intents the SDK and the facilitator build.
#[test]
fn production_router_matches_the_harness() {
    use kob_protocol::router::{IntentKind, IntentState, ACTORS};
    let f = fx();
    let (payer, merchant) = (pk(&f.payer), pk(&f.merchant));
    for a in ACTORS.iter().filter(|a| a.shape.a_family == kob_protocol::Family::Kcc20) {
        let shape = a.name.split_once('_').unwrap().1;
        let (art, state) = match a.shape.kind {
            IntentKind::KasToToken => (
                k2t_art_s(Router::Shipped, shape, &payer, &merchant, TOKEN_B, WHOLE, ASK_PRICE, MAX_EXTRA),
                IntentState::KasToToken {
                    payer,
                    merchant,
                    token: TOKEN_B.as_bytes(),
                    program: kob_protocol::artifacts::TemplateId::Kcc20Ref8x8,
                    amount: WHOLE,
                    max_pay: ASK_PRICE,
                    max_extra: MAX_EXTRA,
                    deadline: DEADLINE,
                },
            ),
            IntentKind::TokenToKas => (
                t2k_art_s(Router::Shipped, shape, &payer, &merchant, TOKEN_A, MERCHANT_KAS, WHOLE),
                IntentState::TokenToKas {
                    payer,
                    merchant,
                    token: TOKEN_A.as_bytes(),
                    program: kob_protocol::artifacts::TemplateId::Kcc20Ref8x8,
                    merchant_kas: MERCHANT_KAS,
                    max_sell: WHOLE,
                    deadline: DEADLINE,
                },
            ),
            IntentKind::TokenSwap => (
                swap_art_s(Router::Shipped, shape, &payer, &merchant, TOKEN_A, TOKEN_B, WHOLE, 2 * WHOLE),
                IntentState::TokenSwap {
                    payer,
                    merchant,
                    token_a: TOKEN_A.as_bytes(),
                    program_a: kob_protocol::artifacts::TemplateId::Kcc20Ref8x8,
                    token_b: TOKEN_B.as_bytes(),
                    program_b: kob_protocol::artifacts::TemplateId::Kcc20Ref8x8,
                    max_sell_a: WHOLE,
                    amount_b: 2 * WHOLE,
                    deadline: DEADLINE,
                },
            ),
        };
        assert_eq!(common::template_hash(&art), a.template().hash, "{}: template hash", a.name);
        assert_eq!(bytecode(&art), state.redeem(a).unwrap(), "{}: instance script", a.name);
    }
}
