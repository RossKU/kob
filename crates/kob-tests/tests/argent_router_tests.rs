/// The order program: the shipped one, or a same-layout impostor (a one-constant edit of the
/// source: validates itself, has another template).
#[derive(Clone, Copy, PartialEq)]
enum Prog {
    Shipped,
    Impostor,
}
fn order_src(name: &str, prog: Prog) -> String {
    let s = src(name);
    match prog {
        Prog::Shipped => s,
        Prog::Impostor => {
            let edited = s.replace("int constant MAX_IDLE = 77760000;", "int constant MAX_IDLE = 77760001;");
            assert_ne!(edited, s, "impostor edit must change the source");
            edited
        }
    }
}
