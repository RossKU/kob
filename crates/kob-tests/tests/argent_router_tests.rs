// ---------------------------------------------------------------- R1: KAS -> token B (KasToToken)

/// Base units bought by the R1 fill (4 whole tokens).
const BUY: i64 = 4 * WHOLE;
const BUDGET: i64 = 30 * KAS; // KasToToken intent value
const MAX_EXTRA: i64 = 11 * KAS; // merchant carrier + fee

/// Parameters of one KasToToken run.
#[derive(Clone)]
struct K2T {
    router: Router,
    /// order program and its terms
    prog: Prog,
    ask: AskP,
    /// base units the ask fills (delivered to the merchant)
    n: i64,
    /// intent terms
    amount: i64,
    max_pay: i64,
    /// covenant ids
    a: Hash,
    r: Hash,
    /// payer key (differs from `fx.payer` only in the self-trade case)
    payer: [u8; 32],
}
fn k2t_default(f: &Fx) -> K2T {
    K2T {
        router: Router::Shipped,
        prog: Prog::Shipped,
        ask: AskP::new(pk(&f.maker_a)),
        n: BUY,
        amount: BUY,
        max_pay: quote_up(BUY, ASK_PRICE),
        a: cov(0xa1),
        r: cov(0xc1),
        payer: pk(&f.payer),
    }
}
/// A KasToToken run filling `n` base units of `ask` (intent amount n, max_pay the ask's quote of n).
fn k2t_fill(f: &Fx, ask: AskP, n: i64) -> K2T {
    K2T { max_pay: quote_up(n, ask.price), ask, n, amount: n, ..k2t_default(f) }
}

/// R1 shape (KAS -> B through a KasToToken intent, one ask, partial fill):
///   in  [0] ask.settle(n base units)  [1] escrow token B (leader, owned by the ask)  [2] intent.buy
///   out [0] maker payout  [1] escrow change  [2] payer change  [3] merchant delivery  [4] ask continuation
/// The maker is paid its all-in proceeds ceil(n * (price - tip) / scale); the payer pays the ask's quote
/// ceil(n * price / scale) (the tip is the keeper's).
fn r1(f: &Fx, p: &K2T, name: &str) -> Scn {
    let t = &f.t;
    let merchant = pk(&f.merchant);
    let ask = ask_art(t, TOKEN_B, &p.ask, p.prog);
    let intent = k2t_art(p.router, &p.payer, &merchant, TOKEN_B, p.amount, p.max_pay, MAX_EXTRA);
    let a = p.a;
    let n = p.n;
    let custody = p.ask.amount;
    let payout = quote_up(n, p.ask.price - p.ask.tip);
    let mut buy_args = vec![bytes(&a.as_bytes())];
    if p.router == Router::NaiveBuy {
        buy_args.push(int(2)); // change_out: honest keeper
    }
    buy_args.extend(handle_lens(&ask_art(t, TOKEN_B, &AskP::new([1; 32]), Prog::Shipped)));
    buy_args.extend(t.hidden());
    Scn {
        lock: 0,
        name: name.into(),
        inputs: vec![
            call(&ask, CARRIER, a, "settle", vec![nb(n), iv(1), iv(1), iv(0)], "ask"),
            tok_leader(
                t,
                TOKEN_B,
                CARRIER,
                custody,
                &a.as_bytes(),
                0,
                vec![tok_state(custody - n, &a.as_bytes(), SCHEME_COVID), tok_state(n, &merchant, SCHEME_P2PK)],
            ),
            call(&intent, BUDGET, p.r, "buy", buy_args.into_iter().map(av).collect(), "k2t"),
        ],
        outputs: vec![
            out(payout, p2pk_spk(&p.ask.maker), None),
            out(CARRIER, t.spk(custody - n, &a.as_bytes(), SCHEME_COVID), Some((1, TOKEN_B))),
            out(BUDGET - quote_up(n, p.ask.price) - CARRIER - FEE, p2pk_spk(&p.payer), None),
            out(CARRIER, t.spk(n, &merchant, SCHEME_P2PK), Some((1, TOKEN_B))),
            out(CARRIER, spk_of(&ask_rest(t, TOKEN_B, &p.ask, p.prog, n)), Some((0, a))),
        ],
    }
}

// ---------------------------------------------------------------- R2: token A -> KAS (TokenToKas)

/// Base units sold by the R2 fill (4 whole tokens).
const SELL: i64 = 4 * WHOLE;
/// Base units of token A the TokenToKas / TokenSwap intents hold (7 whole tokens).
const HELD: i64 = 7 * WHOLE;
const MERCHANT_KAS: i64 = 9 * KAS;
const BID_VALUE: i64 = 55 * KAS;

#[derive(Clone)]
struct T2K {
    prog: Prog,
    bid: BidP,
    /// base units sold into the bid (the rest of HELD is the payer's change)
    n: i64,
    /// intent terms
    max_sell: i64,
    merchant_kas: i64,
    b: Hash,
    r: Hash,
    payer: [u8; 32],
}
fn t2k_default(f: &Fx) -> T2K {
    T2K {
        prog: Prog::Shipped,
        bid: BidP::new(pk(&f.maker_b)),
        n: SELL,
        max_sell: SELL,
        merchant_kas: MERCHANT_KAS,
        b: cov(0xb1),
        r: cov(0xc2),
        payer: pk(&f.payer),
    }
}

/// R2 shape (A -> KAS through a TokenToKas intent that owns the payer's tokens, one bid, partial):
///   in  [0] bid.fill(n base units)  [1] token A (leader, owned by the intent)  [2] intent.sell
///   out [0] bid delivery (token to the bid maker)  [1] bid continuation  [2] merchant KAS
///       [3] payer token change  [4] keeper KAS
/// The bid consumes used = ceil(n * (price + tip) / scale) of its escrow and pays at most
/// allIn = floor(n * (price + tip) / scale); used - allIn rides on its delivery.
fn r2(f: &Fx, p: &T2K, name: &str) -> Scn {
    let t = &f.t;
    let merchant = pk(&f.merchant);
    let bid = bid_art(t, TOKEN_A, &p.bid, p.prog);
    let intent = t2k_art(&p.payer, &merchant, TOKEN_A, p.merchant_kas, p.max_sell);
    let (b, r) = (p.b, p.r);
    let n = p.n;
    let used = quote_up(n, p.bid.price);
    let all_in = quote_down(n, p.bid.price);
    let cont = BID_VALUE - used - DC;
    let delivery = DC + used - all_in;
    let intent_value = CARRIER;
    let keeper = BID_VALUE + CARRIER + intent_value - delivery - cont - p.merchant_kas - CARRIER - FEE;
    let mut sell_args = vec![bytes(&b.as_bytes()), int(n)];
    sell_args.extend(handle_lens(&bid_art(t, TOKEN_A, &BidP::new([1; 32]), Prog::Shipped)));
    sell_args.extend(t.hidden());
    Scn {
        lock: 0,
        name: name.into(),
        inputs: vec![
            call(&bid, BID_VALUE, b, "fill", vec![nb(n), iv(1), iv(0)], "bid"),
            tok_leader(
                t,
                TOKEN_A,
                CARRIER,
                HELD,
                &r.as_bytes(),
                0,
                vec![tok_state(n, &p.bid.maker, SCHEME_P2PK), tok_state(HELD - n, &p.payer, SCHEME_P2PK)],
            ),
            call(&intent, intent_value, r, "sell", sell_args.into_iter().map(av).collect(), "t2k"),
        ],
        outputs: vec![
            out(delivery, t.spk(n, &p.bid.maker, SCHEME_P2PK), Some((1, TOKEN_A))),
            out(cont, spk_of(&bid), Some((0, b))),
            out(p.merchant_kas, p2pk_spk(&merchant), None),
            out(CARRIER, t.spk(HELD - n, &p.payer, SCHEME_P2PK), Some((1, TOKEN_A))),
            out(keeper, p2pk_spk(&pk(&f.keeper)), None),
        ],
    }
}

// ---------------------------------------------------------------- R3: token A -> KAS -> token B (TokenSwap)

const SWAP_SELL: i64 = 4 * WHOLE; // token A base units into the bid
const SWAP_BUY: i64 = 3 * WHOLE; // token B base units out of the ask
const SWAP_INTENT_VALUE: i64 = CARRIER;

#[derive(Clone)]
struct Swap {
    prog: Prog,
    bid: BidP,
    ask: AskP,
    max_sell_a: i64,
    amount_b: i64,
    token_b: Hash,
    b: Hash,
    a: Hash,
    r: Hash,
    payer: [u8; 32],
}
fn swap_default(f: &Fx) -> Swap {
    Swap {
        prog: Prog::Shipped,
        bid: BidP::new(pk(&f.maker_b)),
        ask: AskP::new(pk(&f.maker_a)),
        max_sell_a: SWAP_SELL,
        amount_b: SWAP_BUY,
        token_b: TOKEN_B,
        b: cov(0xb1),
        a: cov(0xa1),
        r: cov(0xc3),
        payer: pk(&f.payer),
    }
}

/// R3 shape (token A -> KAS -> token B, one bid of A and one ask of B, both partial):
///   in  [0] bid.fill(4000)  [1] ask.settle(3000)  [2] token A (leader, owned by the intent)
///       [3] escrow B (leader, owned by the ask)  [4] intent.swap
///   out [0] A delivery (bid maker)  [1] ask maker payout  [2] escrow B change  [3] bid continuation
///       [4] merchant delivery (B)  [5] payer A change  [6] ask continuation  [7] keeper KAS
fn r3(f: &Fx, p: &Swap, name: &str) -> Scn {
    let t = &f.t;
    let merchant = pk(&f.merchant);
    let bid = bid_art(t, TOKEN_A, &p.bid, p.prog);
    let ask = ask_art(t, p.token_b, &p.ask, p.prog);
    let intent = swap_art(&p.payer, &merchant, TOKEN_A, p.token_b, p.max_sell_a, p.amount_b);
    let (b, a, r) = (p.b, p.a, p.r);
    let custody = p.ask.amount;
    let payout = quote_up(SWAP_BUY, p.ask.price - p.ask.tip);
    let (used, all_in) = (quote_up(SWAP_SELL, p.bid.price), quote_down(SWAP_SELL, p.bid.price));
    let delivery = DC + used - all_in;
    let cont = BID_VALUE - used - DC;
    let keeper = BID_VALUE + 3 * CARRIER + SWAP_INTENT_VALUE - delivery - payout - CARRIER - cont - CARRIER - CARRIER - CARRIER - FEE;
    let mut swap_args = vec![bytes(&b.as_bytes()), bytes(&a.as_bytes()), int(SWAP_SELL)];
    swap_args.extend(handle_lens(&ask_art(t, TOKEN_B, &AskP::new([1; 32]), Prog::Shipped)));
    swap_args.extend(handle_lens(&bid_art(t, TOKEN_A, &BidP::new([1; 32]), Prog::Shipped)));
    swap_args.extend(t.hidden()); // token A's handle
    swap_args.extend(t.hidden()); // token B's handle
    Scn {
        lock: 0,
        name: name.into(),
        inputs: vec![
            call(&bid, BID_VALUE, b, "fill", vec![nb(SWAP_SELL), iv(2), iv(0)], "bid"),
            call(&ask, CARRIER, a, "settle", vec![nb(SWAP_BUY), iv(3), iv(2), iv(0)], "ask"),
            tok_leader(
                t,
                TOKEN_A,
                CARRIER,
                HELD,
                &r.as_bytes(),
                0,
                vec![tok_state(SWAP_SELL, &p.bid.maker, SCHEME_P2PK), tok_state(HELD - SWAP_SELL, &p.payer, SCHEME_P2PK)],
            ),
            tok_leader(
                t,
                p.token_b,
                CARRIER,
                custody,
                &a.as_bytes(),
                0,
                vec![tok_state(custody - SWAP_BUY, &a.as_bytes(), SCHEME_COVID), tok_state(SWAP_BUY, &merchant, SCHEME_P2PK)],
            ),
            call(&intent, SWAP_INTENT_VALUE, r, "swap", swap_args.into_iter().map(av).collect(), "swap"),
        ],
        outputs: vec![
            out(delivery, t.spk(SWAP_SELL, &p.bid.maker, SCHEME_P2PK), Some((2, TOKEN_A))),
            out(payout, p2pk_spk(&p.ask.maker), None),
            out(CARRIER, t.spk(custody - SWAP_BUY, &a.as_bytes(), SCHEME_COVID), Some((3, p.token_b))),
            out(cont, spk_of(&bid), Some((0, b))),
            out(CARRIER, t.spk(SWAP_BUY, &merchant, SCHEME_P2PK), Some((3, p.token_b))),
            out(CARRIER, t.spk(HELD - SWAP_SELL, &p.payer, SCHEME_P2PK), Some((2, TOKEN_A))),
            out(CARRIER, spk_of(&ask_rest(t, p.token_b, &p.ask, p.prog, SWAP_BUY)), Some((1, a))),
            out(keeper, p2pk_spk(&pk(&f.keeper)), None),
        ],
    }
}

/// Payer cancel of one intent (SIGHASH_ALL), returning its locked KAS.
fn cancel_scn(intent: &SilAbiArtifact, r: Hash, payer: &Keypair, signer: &Keypair, name: &'static str, label: &'static str) -> Scn {
    Scn {
        lock: 0,
        name: name.into(),
        inputs: vec![Inp {
            entry: cov_utxo(BUDGET, spk_of(intent), r),
            role: Role::Call { art: intent.clone(), entry: "cancel", args: vec![Arg::Sig(*signer, 0x01)], name: label },
        }],
        outputs: vec![out(BUDGET - FEE, p2pk_spk(&pk(payer)), None)],
    }
}

/// The fill shapes of the router: one actor (`<Intent>_<shape>`) each, with that entry, expire and cancel.
const K2T_SHAPES: [&str; 6] = ["buy", "buy_out", "buy2", "buy2_out", "buy3", "buy3_out"];
const T2K_SHAPES: [&str; 6] = ["sell", "sell_out", "sell2", "sell2_out", "sell3", "sell3_out"];
const SWAP_SHAPES: [&str; 6] = ["swap", "swap_bid_out", "swap_ask_out", "swap_out", "swap2", "swap2_out"];
/// (actor name, observes KobAsk, observes KobBid) of every router actor.
fn router_shapes() -> Vec<(String, bool, bool)> {
    let mut v = vec![];
    v.extend(K2T_SHAPES.iter().map(|s| (format!("KasToToken_{s}"), true, false)));
    v.extend(T2K_SHAPES.iter().map(|s| (format!("TokenToKas_{s}"), false, true)));
    v.extend(SWAP_SHAPES.iter().map(|s| (format!("TokenSwap_{s}"), true, true)));
    v
}

