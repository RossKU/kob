    let mut next = leader_next(&s, 1);
    next[0] = tok_state(SELL, &thief, SCHEME_P2PK);
    set_leader_next(&mut s, 1, next);
    run_bad(t, &s, 0);
    // N-T1b: the bid continuation keeps one sompi more than in - ceil budget - carrier (a fill that rounds).
    let odd = T2K { bid: BidP { price: 240_000_003, ..BidP::new(pk(&f.maker_b)) }, n: 3_333, max_sell: 3_333, ..t2k_default(&f) };
    let mut s = r2(&f, &odd, "N-T1b A->KAS: bid continuation consumes one sompi less than the ceil budget");
