/// Quote value of `n` base units at `rate` sompi per whole token, computed exactly as the covenants' `quoteOf`
/// (split product: q = n / scale, m = n % scale; c = scale - 1 for `Round::Up`, what a maker receives and the
/// budget a bid consumes; c = 0 for `Round::Down`, what a maker pays), cross-checked against
/// `kob_protocol::state::quote_of` and the exact 128-bit value.
fn quote(n: i64, rate: i64, round: Round) -> i64 {
    let c = match round {
        Round::Up => SCALE - 1,
        Round::Down => 0,
    };
    let (q, m) = (n / SCALE, n % SCALE);
    let v = q * rate + m * (rate / SCALE) + (m * (rate % SCALE) + c) / SCALE;
    assert_eq!(Some(v), quote_of(n, rate, SCALE, round), "quoteOf mirror differs from kob_protocol ({n} at {rate})");
    let exact = n as i128 * rate as i128;
    let want = match round {
        Round::Up => (exact + SCALE as i128 - 1) / SCALE as i128,
        Round::Down => exact / SCALE as i128,
    };
    assert_eq!(v as i128, want, "quoteOf mirror is not the exact rounded value ({n} at {rate})");
    v
}
/// What a maker receives for `n` base units at `rate` (rounded up).
fn quote_up(n: i64, rate: i64) -> i64 {
    quote(n, rate, Round::Up)
}
/// What a maker pays for `n` base units at `rate` (rounded down).
fn quote_down(n: i64, rate: i64) -> i64 {
    quote(n, rate, Round::Down)
}

