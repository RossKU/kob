    let bid = bid_art(t, TOKEN_A, &BidP::new(pk(&f.payer)), Prog::Shipped);
    let b = cov(0xb9);
    s.inputs.push(call(&bid, BID_VALUE, b, "fill", vec![nb(3 * WHOLE), iv(1), iv(0)], "bid"));
