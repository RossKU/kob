/// The shipped router rejects each of these attacks; a router with the corresponding rule removed
/// (generated source edited and recompiled) accepts the very same transaction.
#[test]
fn router_ablation_sweeps() {
    let f = fx();
    let t = &f.t;
    let thief = pk(&f.thief);

    // the sweep's price bound is over the sum of the asks' quotes.
    let mk = |router: Router| {
        let mut p = k2tm(&f, &[(3, 3), (10, 4)]);
        p.router = router;
        p.max_pay = Some(10 * KAS);
        k2t_multi(&f, &p, "A-M1 buy2: sum of the quotes (17.5 KAS) above max_pay (10 KAS)")
    };
    run_attack_passes(t, &mk(Router::BuyPerLegPrice));
    run_bad(t, &mk(Router::Shipped), 4);

    // the sweep's max_sell is over the sum of the bids.
    let mk = |router: Router| {
        let mut p = t2km(&f, bid_legs(&[(3, true), (4, false)]));
        p.router = router;
        p.max_sell = Some(5 * WHOLE);
        t2k_multi(&f, &p, "A-M2 sell2: 7000 base units sold over two bids, max_sell is 5000")
    };
    run_attack_passes(t, &mk(Router::SellPerLegBound));
    run_bad(t, &mk(Router::Shipped), 3);

    // the positional rule holds in a sweep: the self-trading payer's change cannot be folded
    // onto ask 2's payout.
    let mk = |router: Router| {
        let mut p = k2tm(&f, &[(3, 3), (10, 4)]);
        p.router = router;
        p.legs[1].p.maker = p.payer;
        let mut s = k2t_multi(&f, &p, "A-M3 buy2 self-trade: payer change aliased onto ask 2's payout out[1]");
        let (change, payout2) = (s.outputs[4].value as i64, s.outputs[1].value as i64);
        s.outputs[1] = out(change, p2pk_spk(&p.payer), None);
        s.outputs[4] = out(payout2, p2pk_spk(&thief), None);
        if router == Router::NaiveBuy2 {
            set_arg(&mut s, 4, 2, iv(1));
        }
        s
    };
    run_attack_passes(t, &mk(Router::NaiveBuy2));
    run_bad(t, &mk(Router::Shipped), 4);

    // the swap sweep's max_sell_a is over the sum of the bids.
    let mk = |router: Router| {
        let mut p = swm(&f, bid_legs(&[(3, true), (4, false)]), ask_legs(&[(2, 2), (10, 3)]));
        p.router = router;
        p.max_sell_a = Some(5 * WHOLE);
        swap_multi(&f, &p, "A-M4 swap2: 7000 base units of A sold over two bids, max_sell_a is 5000")
    };
    run_attack_passes(t, &mk(Router::SwapPerLegBound));
    run_bad(t, &mk(Router::Shipped), 7);
}

