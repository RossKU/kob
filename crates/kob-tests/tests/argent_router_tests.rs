//! KOB router (contracts/argent/kob_router.ag): the Argent composition layer on top of the
//! hand-written protocol v3 orders, executed in rusty-kaspa v2.1.0's TxScriptEngine with KIP-20 covenant
//! context and script-unit metering.
//!
//! - Orders: `contracts/v2/KobAsk.sil` / `KobBid.sil`, hand-written, per-order values in the
//!   state span (one template per kind). They validate themselves in every transaction
//!   (custody C7, stray guards, auctions, IOC/FOK kill included). Amounts are base units of the token,
//!   prices sompi per whole token (`scale` = 10^decimals base units, here SCALE = 1000), quote values rounded
//!   in the maker's favour exactly as the covenants' `quoteOf` (see `quote`).
//! - Router: `contracts/argent/router/sil/*.sil`, generated by argentc from `kob_router.ag`. It
//!   links the orders by CLOSED ICC (the KOBOrders artifact) and observes the tokens by OPEN ICC: every
//!   intent's state carries its token program handle (here the handle of the published KOBToken).
//! - Token: `contracts/kcc20/variants/KCC20Ref_8x8.sil`, the token KOB issues (8 in / 8 out). The other
//!   programs (the 3/3 reference program, the KRON programs with `KobBidKron`) run every router actor in
//!   `kob-protocol/tests/intent_builders.rs` through the production builders; the KRON cancel's lock check
//!   and its ablation are in `c4_security_tests.rs`.
//!
//! Intents (payment intents any keeper can execute): KasToToken, TokenToKas, TokenSwap
//! (token A -> KAS -> token B); each one has a payer `cancel`. Each intent has one entry per fill
//! shape: an order RESTS (partial fill, it continues) or ENDS (sold-out ask, exhausted / IOC / FOK
//! bid), and up to 3 orders (2 per leg for swaps) are swept in one transaction.
//!
//! Positive: R1* (KAS -> B), R2* (A -> KAS), R3* (A -> KAS -> B), R4* (payer cancel; a token intent's with its lock);
//!   R6* R7* (KasToToken sold-out, sweeps, auctions), R8* (TokenToKas), R9* (TokenSwap).
//! Negative: N-K* / N-T* / N-S* reject at the stated input. The positional anti-aliasing rule and
//! the price and `max_sell` bounds are shown necessary by ablation: the same tx validates on a
//! router with the rule removed (`A-*`), which is generated by editing the committed generated
//! source and recompiling.
//!
//! Run: cargo test --release -p kob-tests --test argent_router_tests -- --nocapture --test-threads=1

