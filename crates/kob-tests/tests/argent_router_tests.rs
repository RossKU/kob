/// Template hash (handle) the committed Argent artifact publishes for `actor` of `app`.
fn published_handle(app: &str, actor: &str) -> Vec<u8> {
    let path = common::repo_root().join(format!("contracts/argent/{app}/artifact.json"));
    let json: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(&path).expect("read artifact")).expect("parse artifact");
    let t = json["argent"]["template_plan"]["templates"]
        .as_array()
        .expect("templates")
        .iter()
        .find(|t| t["actor"] == actor)
        .unwrap_or_else(|| panic!("{app} has no actor {actor}"));
    t["actor_type_handle"]["template"]["hash"].as_array().expect("hash").iter().map(|b| b.as_u64().unwrap() as u8).collect()
}

/// The open ICC token handle every harness intent names: the published KOBToken program (the harness token).
fn tok_handle() -> ArtifactValue {
    bytes(&published_handle("KOBToken", "KCC20"))
}

