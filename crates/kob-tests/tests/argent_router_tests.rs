/// The payer's cancel of a token intent (`TokenToKas_sell` or `TokenSwap_swap`) holding HELD base units of token A, signed by
/// `signer`; `tokens_to`: the owner they go to (`None`: the lock is left out of the transaction).
///   in  [0] intent.cancel  [1] token A (leader, owned by the intent)
///   out [0] payer KAS  [1] the HELD base units
fn token_cancel(f: &Fx, swap: bool, signer: &Keypair, tokens_to: Option<&[u8; 32]>, name: &str) -> Scn {
    let t = &f.t;
    let (payer, merchant) = (pk(&f.payer), pk(&f.merchant));
    let (intent, r, label) = if swap {
        (swap_art(&payer, &merchant, TOKEN_A, TOKEN_B, WHOLE, WHOLE), cov(0xc3), "swap")
    } else {
        (t2k_art(&payer, &merchant, TOKEN_A, MERCHANT_KAS, WHOLE), cov(0xc2), "t2k")
    };
    let mut cancel_args = vec![Arg::Sig(*signer, 0x01)];
    cancel_args.extend(t.hidden().into_iter().map(av));
    let mut inputs = vec![call(&intent, CARRIER, r, "cancel", cancel_args, label)];
    let mut outputs = vec![out(CARRIER - FEE, p2pk_spk(&payer), None)];
    if let Some(to) = tokens_to {
        inputs.push(tok_leader(t, TOKEN_A, CARRIER, HELD, &r.as_bytes(), 0, vec![tok_state(HELD, to, SCHEME_P2PK)]));
        outputs.push(out(CARRIER, t.spk(HELD, to, SCHEME_P2PK), Some((1, TOKEN_A))));
    }
    Scn { lock: 0, name: name.into(), inputs, outputs }
}

/// C5 X-1: the cancel of a token intent must spend the locked tokens (input j + 1). Without them the cancel would end the
/// intent covenant and the tokens (owned by its id) could never move again; the router refuses it even signed by the
/// payer. Where the tokens go is the payer's signed choice; a thief's signature fails.
#[test]
fn router_token_cancel_returns_the_lock() {
    let f = fx();
    let t = &f.t;
    let (payer, thief) = (pk(&f.payer), pk(&f.thief));
    for swap in [false, true] {
        let kind = if swap { "TokenSwap" } else { "TokenToKas" };
        run_ok(t, &token_cancel(&f, swap, &f.payer, Some(&payer), "C1 payer cancels a token intent with its lock"));
        let name = format!("N-C1 {kind}: payer cancels without the lock (the tokens would be orphaned)");
        run_bad(t, &token_cancel(&f, swap, &f.payer, None, &name), 0);
        let name = format!("N-C2 {kind}: thief cancels with the lock to itself");
        run_bad(t, &token_cancel(&f, swap, &f.thief, Some(&thief), &name), 0);
    }
}

