#[test]
fn router_artifacts_link_the_published_handles() {
    // The generated router embeds exactly the handles KOB publishes for the orders (the order templates of the
    // KOBOrders artifact); the token programs are open ICC handles in each intent's state, never linked (the harness
    // intents name the 8/8 token of KOBToken, asserted for the token in Token::new).
    let f = fx();
    let ask_hash = compiled_template_parts_and_hash(&ask_art(&f.t, TOKEN_B, &AskP::new([1; 32]), Prog::Shipped)).2;
    let bid_hash = compiled_template_parts_and_hash(&bid_art(&f.t, TOKEN_A, &BidP::new([1; 32]), Prog::Shipped)).2;
    assert_eq!(ask_hash, published_handle("KOBOrders", "KobAsk"));
    assert_eq!(bid_hash, published_handle("KOBOrders", "KobBid"));
    let hex = |h: &[u8]| h.iter().map(|b| format!("{b:02x}")).collect::<String>();
    // Every fill shape is its own actor; each one links the handles of the orders it observes.
    for (name, asks, bids) in router_shapes() {
        let src = src(&name);
        assert!(!src.contains(&hex(&f.t.hash)), "{name} links no token program (open ICC)");
        assert!(src.contains("token_type") || src.contains("token_a_type"), "{name} reads its tokens under a state handle");
        assert_eq!(src.contains(&hex(&ask_hash)), asks, "{name} links the published KobAsk handle exactly when it observes asks");
        assert_eq!(src.contains(&hex(&bid_hash)), bids, "{name} links the published KobBid handle exactly when it observes bids");
    }
    // The orders are one template per kind: two different orders share the handle.
    let other =
        ask_art(&f.t, TOKEN_B, &AskP { maker: pk(&f.thief), price: 7 * KAS, tip: 5, tif: 2, ..AskP::new([1; 32]) }, Prog::Shipped);
    assert_eq!(compiled_template_parts_and_hash(&other).2, ask_hash);
    // An impostor with the same layout has another template.
    let impostor = ask_art(&f.t, TOKEN_B, &AskP::new([1; 32]), Prog::Impostor);
    assert_ne!(compiled_template_parts_and_hash(&impostor).2, ask_hash);
    println!(
        "SIZES redeem B: KobAsk {}, KobBid {}",
        bytecode(&ask_art(&f.t, TOKEN_B, &AskP::new([1; 32]), Prog::Shipped)).len(),
        bytecode(&bid_art(&f.t, TOKEN_A, &BidP::new([1; 32]), Prog::Shipped)).len(),
    );
    for shape in K2T_SHAPES {
        println!(
            "SIZES redeem KasToToken_{shape}: {} B",
            bytecode(&k2t_art_s(Router::Shipped, shape, &[1; 32], &[1; 32], TOKEN_B, WHOLE, 1, 1)).len()
        );
    }
    for shape in T2K_SHAPES {
        println!(
            "SIZES redeem TokenToKas_{shape}: {} B",
            bytecode(&t2k_art_s(Router::Shipped, shape, &[1; 32], &[1; 32], TOKEN_A, 1, 1)).len()
        );
    }
    for shape in SWAP_SHAPES {
        println!(
            "SIZES redeem TokenSwap_{shape}: {} B",
            bytecode(&swap_art_s(Router::Shipped, shape, &[1; 32], &[1; 32], TOKEN_A, TOKEN_B, 1, 1)).len()
        );
    }
}

#[test]
fn router_positive() {
    let f = fx();
    run_ok(&f.t, &r1(&f, &k2t_default(&f), "R1 KAS->B via KasToToken: 1 ask, 4000 of 10000 base units to merchant"));
    // The ask carries a priority tip: it takes less than its quote, the payer's bound is the quote.
    let tipped = K2T { ask: AskP { tip: 100_000, ..AskP::new(pk(&f.maker_a)) }, ..k2t_default(&f) };
    run_ok(&f.t, &r1(&f, &tipped, "R1b KAS->B: ask with a priority tip (maker paid quote - tip)"));
    // Rounding: 4321 base units (not a multiple of the scale) at a price that is not a multiple of the scale: the maker
    // is paid the ceil of its all-in proceeds, the payer's bound is the ceil of the quote.
    let odd = AskP { price: 250_000_007, tip: 100_003, ..AskP::new(pk(&f.maker_a)) };
    assert_ne!(quote_up(4_321, odd.price - odd.tip), quote_down(4_321, odd.price - odd.tip), "the fill must round");
    run_ok(&f.t, &r1(&f, &k2t_fill(&f, odd, 4_321), "R1c KAS->B: 4321 base units at 2.50000007 tip 0.00100003 (ceil proceeds)"));
    run_ok(&f.t, &r2(&f, &t2k_default(&f), "R2 A->KAS via TokenToKas: 4000 base units into 1 bid, merchant paid 9 KAS"));
    // Rounding: 3333 base units into a bid at 2.40000003: the escrow is consumed at the ceil, the maker pays the floor,
    // the difference rides on its delivery.
    let odd = T2K { bid: BidP { price: 240_000_003, ..BidP::new(pk(&f.maker_b)) }, n: 3_333, max_sell: 3_333, ..t2k_default(&f) };
    assert_eq!(quote_up(3_333, 240_000_003), quote_down(3_333, 240_000_003) + 1, "the fill must round");
    run_ok(&f.t, &r2(&f, &odd, "R2b A->KAS: 3333 base units into a bid at 2.40000003 (ceil budget, floor spend)"));
    run_ok(&f.t, &r3(&f, &swap_default(&f), "R3 A->KAS->B via TokenSwap: 4000 base units into a bid, 3000 out of an ask"));
}

