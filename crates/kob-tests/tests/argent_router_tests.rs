/// Expiry of a KasToToken intent (anyone, from the deadline on): [0] intent.expire -> [0] payer KAS.
fn expire_k2t(f: &Fx, lock: u64, kas_to: &[u8; 32], kas: i64, name: &str) -> Scn {
    let intent = k2t_art(Router::Shipped, &pk(&f.payer), &pk(&f.merchant), TOKEN_B, WHOLE, ASK_PRICE, MAX_EXTRA);
    Scn {
        lock,
        name: name.into(),
        inputs: vec![call(&intent, BUDGET, cov(0xc1), "expire", vec![], "k2t")],
        outputs: vec![out(kas, p2pk_spk(kas_to), None)],
    }
}

/// Expiry of a token intent (`TokenToKas_sell` or `TokenSwap_swap`) that holds HELD base units of token A:
///   in  [0] intent.expire  [1] token A (leader, owned by the intent)
///   out [0] payer KAS  [1] the HELD base units back to the payer's key
fn expire_tokens(f: &Fx, swap: bool, lock: u64, name: &str) -> Scn {
    let t = &f.t;
    let (payer, merchant) = (pk(&f.payer), pk(&f.merchant));
    let (intent, r, label) = if swap {
        (swap_art(&payer, &merchant, TOKEN_A, TOKEN_B, WHOLE, WHOLE), cov(0xc3), "swap")
    } else {
        (t2k_art(&payer, &merchant, TOKEN_A, MERCHANT_KAS, WHOLE), cov(0xc2), "t2k")
    };
    let args = t.hidden().into_iter().map(av).collect();
    Scn {
        lock,
        name: name.into(),
        inputs: vec![
            call(&intent, CARRIER, r, "expire", args, label),
            tok_leader(t, TOKEN_A, CARRIER, HELD, &r.as_bytes(), 0, vec![tok_state(HELD, &payer, SCHEME_P2PK)]),
        ],
        outputs: vec![out(CARRIER - FEE, p2pk_spk(&payer), None), out(CARRIER, t.spk(HELD, &payer, SCHEME_P2PK), Some((1, TOKEN_A)))],
    }
}

/// From its deadline on, anyone may expire an intent (CLTV, `tx.time >= deadline`): the KAS back to the payer (less at
/// most EXPIRE_MAX_FEE) and the locked tokens, whole, to the payer's key. Before the deadline the expiry rejects. The
/// payer's cancel works before and after the deadline. (A covenant cannot refuse an execution by the clock, there is no
/// upper time bound in a CLTV; the expiry is what ends an abandoned intent.)
#[test]
fn router_deadline_expire_and_cancel() {
    let f = fx();
    let t = &f.t;
    let (payer, thief) = (pk(&f.payer), pk(&f.thief));
    let at = DEADLINE as u64;
    // positive
    run_ok(t, &expire_k2t(&f, at, &payer, BUDGET - FEE, "E1 KasToToken expired at the deadline: KAS back to the payer"));
    run_ok(t, &expire_k2t(&f, at + 1, &payer, BUDGET - EXPIRE_MAX_FEE, "E1b KasToToken expired, the expirer keeps EXPIRE_MAX_FEE"));
    run_ok(t, &expire_tokens(&f, false, at, "E2 TokenToKas expired: KAS and the locked tokens back to the payer"));
    run_ok(t, &expire_tokens(&f, true, at + 60_000, "E3 TokenSwap expired: KAS and the locked tokens back to the payer"));
    let (pkm, merchant) = (pk(&f.payer), pk(&f.merchant));
    for (lock, when) in [(0u64, "before"), (at + 1, "after")] {
        let k2t = k2t_art(Router::Shipped, &pkm, &merchant, TOKEN_B, WHOLE, ASK_PRICE, MAX_EXTRA);
        let mut s = cancel_scn(&k2t, cov(0xc1), &f.payer, &f.payer, "E4 payer cancels a KasToToken intent", "k2t");
        s.lock = lock;
        s.name = format!("E4 payer cancels a KasToToken intent {when} its deadline");
        run_ok(t, &s);
    }

    // negative: the clock
    run_bad(t, &expire_k2t(&f, at - 1, &payer, BUDGET - FEE, "N-E1 KasToToken expired 1 ms before the deadline"), 0);
    run_bad(t, &expire_k2t(&f, 0, &payer, BUDGET - FEE, "N-E2 KasToToken expired without a time lock"), 0);
    run_bad(t, &expire_k2t(&f, 1_000_000, &payer, BUDGET - FEE, "N-E3 KasToToken expired under a DAA lock"), 0);
    run_bad(t, &expire_tokens(&f, false, at - 1, "N-E4 TokenToKas expired before the deadline"), 0);
    run_bad(t, &expire_tokens(&f, true, at - 1, "N-E5 TokenSwap expired before the deadline"), 0);
    // negative: where the KAS goes
    run_bad(t, &expire_k2t(&f, at, &thief, BUDGET - FEE, "N-E6 KasToToken expiry pays the thief"), 0);
    run_bad(t, &expire_k2t(&f, at, &payer, BUDGET - EXPIRE_MAX_FEE - 1, "N-E7 the expirer keeps more than EXPIRE_MAX_FEE"), 0);
    let mut s = expire_tokens(&f, false, at, "N-E8 TokenToKas expiry pays the intent's KAS to the thief");
    s.outputs[0] = out(CARRIER - FEE, p2pk_spk(&thief), None);
    run_bad(t, &s, 0);
    // negative: where the tokens go
    for swap in [false, true] {
        let mut s = expire_tokens(
            &f,
            swap,
            at,
            if swap { "N-E9b TokenSwap expiry: tokens to the thief" } else { "N-E9 TokenToKas expiry: tokens to the thief" },
        );
        s.outputs[1] = out(CARRIER, t.spk(HELD, &thief, SCHEME_P2PK), Some((1, TOKEN_A)));
        set_leader_next(&mut s, 1, vec![tok_state(HELD, &thief, SCHEME_P2PK)]);
        run_bad(t, &s, 0);
    }
    let mut s = expire_tokens(&f, false, at, "N-E10 TokenToKas expiry: 6000 of the 7000 base units back, 1000 to the thief");
    s.outputs[1] = out(CARRIER / 2, t.spk(6 * WHOLE, &payer, SCHEME_P2PK), Some((1, TOKEN_A)));
    s.outputs.push(out(CARRIER / 2, t.spk(WHOLE, &thief, SCHEME_P2PK), Some((1, TOKEN_A))));
    set_leader_next(&mut s, 1, vec![tok_state(6 * WHOLE, &payer, SCHEME_P2PK), tok_state(WHOLE, &thief, SCHEME_P2PK)]);
    run_bad(t, &s, 0);
    let mut s = expire_tokens(&f, false, at, "N-E11 TokenToKas expiry: tokens back with borrowing enabled");
    let borrowing: ArtifactValue = BTreeMap::from([
        ("amount".to_string(), int(HELD)),
        ("owner".to_string(), bytes(&payer)),
        ("owner_scheme".to_string(), ArtifactValue::Byte(SCHEME_P2PK)),
        ("borrow_scheme".to_string(), ArtifactValue::Byte(1)),
        ("borrow_guard".to_string(), bytes(&[0u8; 32])),
        ("extension_commitment".to_string(), bytes(&EXT)),
    ])
    .into();
    s.outputs[1] = out(CARRIER, pay_to_script_hash_script(&t.redeem(HELD, &payer, SCHEME_P2PK, 1)), Some((1, TOKEN_A)));
    set_leader_next(&mut s, 1, vec![borrowing]);
    run_bad(t, &s, 0);
    // negative: the token input is not at j + 1 (then another input's positional rule could claim out j + 1)
    let mut s = expire_tokens(&f, false, at, "N-E12 TokenToKas expiry with the locked tokens before the intent");
    s.inputs.swap(0, 1);
    s.outputs = vec![
        out(0, p2pk_spk(&pk(&f.keeper)), None),
        out(CARRIER - FEE, p2pk_spk(&payer), None),
        out(CARRIER, t.spk(HELD, &payer, SCHEME_P2PK), Some((0, TOKEN_A))),
    ];
    run_bad(t, &s, 1);
    // negative (C5 X-6): the expirer keeps at most EXPIRE_MAX_FEE in all, so the lock carrier comes back whole
    for swap in [false, true] {
        let mut s = expire_tokens(&f, swap, at, "N-E13 token intent expiry: the expirer keeps four fifths of the lock carrier");
        s.outputs[1] = out(CARRIER / 5, t.spk(HELD, &payer, SCHEME_P2PK), Some((1, TOKEN_A)));
        s.outputs.push(out(CARRIER - CARRIER / 5, p2pk_spk(&thief), None));
        run_bad(t, &s, 0);
    }
}

