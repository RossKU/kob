/// The third-party example `contracts/argent/examples/closed_icc_gate.ag` (PriceGate, published SilverScript under
/// `contracts/argent/examples-out/`): a KAS lock spendable beside a partial fill of a KobAsk quoting at most
/// `max_price`. Every partial fill continues with the remaining amount minus `n`; the gate pins exactly that continuation for the `n` it is
/// given. Before the fix the example required an UNCHANGED continuation, which never occurs, so a gate built from it
/// could never be spent. [0] ask fills 4000 base units, [1] its escrow, [2] the gate; the owner signs.
fn fx_gate_spend(f: &Fx, n_gate: i64) -> Scn {
    let t = &f.t;
    let p = AskP::new(pk(&f.merchant));
    let a = cov(0xa1);
    let ask = ask_art(t, TOKEN_B, &p, Prog::Shipped);
    let gate = compile_contract(&src("PriceGate"), &[bytes(&pk(&f.payer)), int(ASK_PRICE)], CompileOptions::default())
        .unwrap_or_else(|e| panic!("compile PriceGate: {e:?}"));
    let taker = pk(&f.keeper);
    let gate_value = 50 * KAS;
    let mut args = vec![av(bytes(&a.as_bytes())), iv(n_gate), Arg::Sig(f.payer, 0x01)];
    args.extend(handle_lens(&ask_art(t, TOKEN_B, &AskP::new([1; 32]), Prog::Shipped)).into_iter().map(av));
    let payout = quote_up(BUY, p.price - p.tip);
    let mut s = Scn {
        lock: 0,
        name: format!("FXG PriceGate (closed-ICC example) spent beside a partial fill of {BUY} base units, gate n = {n_gate}"),
        inputs: vec![
            call(&ask, CARRIER, a, "settle", vec![nb(BUY), iv(1), iv(1), iv(0)], "ask"),
            tok_leader(
                t,
                TOKEN_B,
                CARRIER,
                10 * WHOLE,
                &a.as_bytes(),
                0,
                vec![tok_state(6 * WHOLE, &a.as_bytes(), SCHEME_COVID), tok_state(BUY, &taker, SCHEME_P2PK)],
            ),
            call(&gate, gate_value, cov(0xc7), "spend", args, "gate"),
        ],
        outputs: vec![
            out(payout, p2pk_spk(&p.maker), None),
            out(CARRIER, t.spk(6 * WHOLE, &a.as_bytes(), SCHEME_COVID), Some((1, TOKEN_B))),
            out(0, p2pk_spk(&taker), None),
            out(CARRIER, t.spk(BUY, &taker, SCHEME_P2PK), Some((1, TOKEN_B))),
            out(CARRIER, spk_of(&ask_rest(t, TOKEN_B, &p, Prog::Shipped, BUY)), Some((0, a))),
        ],
    };
    let total_in: i64 = s.inputs.iter().map(|i| i.entry.amount as i64).sum();
    let others: i64 = s.outputs.iter().map(|o| o.value as i64).sum();
    s.outputs[2] = out(total_in - others - FEE, p2pk_spk(&taker), None);
    s
}

#[test]
fn closed_icc_example_gate_is_spendable() {
    let f = fx();
    run_ok(&f.t, &fx_gate_spend(&f, BUY));
    // the gate pins the continuation for ITS n: one base unit off does not match the ask's continuation
    run_bad(&f.t, &fx_gate_spend(&f, BUY - 1), 2);
}

