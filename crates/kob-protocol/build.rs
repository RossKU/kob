//! Generates the token-program part of `TemplateId` and the embedded program sources from the profile table
//! `data/programs.json` (see `src/profile.rs` and `docs/spec/token-programs.md`).
//!
//! Output `$OUT_DIR/token_programs.rs`:
//!
//! * `with_token_programs!(callback)`: invokes `callback! { kcc20: [(Variant, "Name", "doc"), ..], kron: [..] }` with the
//!   programs of each codec family in file order (the enum in `artifacts.rs` places the KCC-20 programs after the KCC-20 order
//!   kinds and the KRON programs last, so the derived ordering of the existing variants never changes);
//! * `TOKEN_PROGRAM_COUNT`;
//! * `embedded_program_source(name)`: the bytes of each program's `source.path` (`include_str!` of a silverc artifact,
//!   `include_bytes!` of a raw redeem script).
//!
//! Only structure is checked here (names, variants, kinds); `profile.rs` checks every fact against the bytes on load.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let repo = manifest.join("../..");
    let data = manifest.join("data/programs.json");
    println!("cargo:rerun-if-changed={}", data.display());
    let text = std::fs::read_to_string(&data).unwrap_or_else(|e| panic!("{}: {e}", data.display()));
    let doc: serde_json::Value = serde_json::from_str(&text).unwrap_or_else(|e| panic!("data/programs.json: {e}"));
    let programs = doc["programs"].as_array().expect("data/programs.json: `programs` array");

    let mut kcc20 = vec![];
    let mut kron = vec![];
    let mut sources = String::new();
    let mut seen = std::collections::BTreeSet::new();
    for p in programs {
        let s = |k: &str| p[k].as_str().unwrap_or_else(|| panic!("data/programs.json: a program without string `{k}`")).to_string();
        let (name, variant, summary) = (s("name"), s("variant"), s("summary"));
        let ident_ok =
            variant.chars().next().is_some_and(|c| c.is_ascii_uppercase()) && variant.chars().all(|c| c.is_ascii_alphanumeric());
        assert!(ident_ok, "data/programs.json: variant `{variant}` must be an UpperCamelCase identifier");
        assert!(
            name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') && !name.is_empty(),
            "data/programs.json: name `{name}` must be [A-Za-z0-9_]+"
        );
        assert!(seen.insert(name.clone()) && seen.insert(format!("variant:{variant}")), "data/programs.json: duplicate {name}");
        let entry = format!("({variant}, {name:?}, {summary:?})");
        match p["codec"].as_str() {
            Some("kcc20") => kcc20.push(entry),
            Some("kron") => kron.push(entry),
            other => panic!("data/programs.json: {name}: unknown codec {other:?}"),
        }
        let path = repo.join(s_path(p, &name));
        println!("cargo:rerun-if-changed={}", path.display());
        assert!(path.is_file(), "data/programs.json: {name}: source {} is not a file", path.display());
        let lit = format!("{:?}", path.to_string_lossy());
        match p["source"]["kind"].as_str() {
            Some("silverc-artifact") => {
                writeln!(sources, "        {name:?} => Some(EmbeddedSource::Artifact(include_str!({lit}))),").unwrap()
            }
            Some("raw-redeem") => writeln!(sources, "        {name:?} => Some(EmbeddedSource::Raw(include_bytes!({lit}))),").unwrap(),
            other => panic!("data/programs.json: {name}: unknown source kind {other:?}"),
        }
    }

    let mut out = String::new();
    out.push_str("// @generated by crates/kob-protocol/build.rs from data/programs.json. Do not edit.\n\n");
    writeln!(out, "/// Number of token programs in `data/programs.json`.").unwrap();
    writeln!(out, "pub const TOKEN_PROGRAM_COUNT: usize = {};\n", kcc20.len() + kron.len()).unwrap();
    writeln!(out, "/// Calls `$m! {{ kcc20: [..], kron: [..] }}` with the token programs of `data/programs.json`.").unwrap();
    writeln!(out, "macro_rules! with_token_programs {{\n    ($m:ident) => {{\n        $m! {{").unwrap();
    writeln!(out, "            kcc20: [{}],", kcc20.join(", ")).unwrap();
    writeln!(out, "            kron: [{}]", kron.join(", ")).unwrap();
    writeln!(out, "        }}\n    }};\n}}\n").unwrap();
    writeln!(out, "/// The embedded bytes of a token program's `source.path`, by program name.").unwrap();
    writeln!(out, "pub(crate) fn embedded_program_source(name: &str) -> Option<EmbeddedSource> {{\n    match name {{").unwrap();
    out.push_str(&sources);
    writeln!(out, "        _ => None,\n    }}\n}}").unwrap();

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("token_programs.rs");
    std::fs::write(&dest, out).unwrap();
}

fn s_path(p: &serde_json::Value, name: &str) -> String {
    p["source"]["path"].as_str().unwrap_or_else(|| panic!("data/programs.json: {name}: no source.path")).to_string()
}
