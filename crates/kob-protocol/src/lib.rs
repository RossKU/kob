//! KOB protocol core.
//!
//! This crate is the single Rust implementation of everything that builds, encodes or checks a
//! KOB transaction. The executor, the CLI and the tests use it natively. The web app and the
//! x402 client SDK use it through `kob-wasm`, so all clients share one code path.
//!
//! # Flow
//!
//! 1. `build::build(&action)` returns a [`tx::BuiltTx`]: the unsigned transaction and its sign
//!    requests.
//! 2. The wallet signs the requests.
//! 3. [`tx::finalize`] adds the signatures and returns a [`tx::SignedTx`].
//! 4. Node RPC `submitTransaction` sends it.
//!
//! # Orders and transactions
//!
//! - [`state`]: the typed state of every order kind in both token families, the token states,
//!   the quote rule ([`state::quote_of`]) and the order arithmetic of each kind.
//! - [`build`]: the builders. They cover create, cancel (with replace and the stray sweep),
//!   refund, kill, close and send, the matcher batches (auctions, triggers, stop entries, repeat
//!   merges), keeper updates, two-token routes and pair orders.
//! - [`tx`]: the unsigned transaction and its signing plan, the fee and mass pass, and the
//!   finalisation with wallet signatures.
//! - [`script`]: signature-script encoding (entry arguments, dispatch tag, redeem push).
//! - [`payload`]: the versioned `KOB1` TLV payload and trustless order recovery.
//! - [`router`]: the KOB router (Argent). Its payment intents are KasToToken, TokenToKas and
//!   TokenSwap, with their pinned actors and states.
//! - [`payment`]: plain KAS payments and sweeps from P2PK coins (`kob send KAS`, `kobd withdraw`).
//! - [`retired`]: the cancel-only table of retired order templates, kept for their makers' cancel.
//! - [`defaults`]: wallet defaults, day orders and per-program keeper tips from measured fees.
//! - [`budget`]: the compute-budget table, generated by the engine over every builder shape.
//! - [`fee_estimate`]: the node's fee estimate (`getFeeEstimate`) and the congestion rule.
//!
//! # Tokens and contracts
//!
//! - [`artifacts`]: the embedded `silverc` artifacts and raw KRON token programs, template-hash
//!   pinning and the network-constant checks.
//! - [`family`]: the token families (KCC-20 and KRON), and only what differs between them.
//! - [`profile`]: the token-program profiles (`data/programs.json`). They hold everything KOB
//!   needs per token program, the codec families and the profile derivation for onboarding.
//! - [`kcc1`]: KCC-1 hash notation, push forms, type names, dispatch tags, and strict argument
//!   and state decoding.
//! - [`kcc2`]: the KCC-2 authority-scheme registry, authority values and minimum approval checks.
//! - [`kcc23`]: the strict codec of a KCC-23 metadata payload, its binding check against a
//!   covenant id, and KOB's token-metadata convention.
//! - [`genesis_states`]: the payload of a token genesis. It holds the states of the token
//!   outputs, so a wallet of the issuing key can find them anywhere.
//! - [`public_mint`]: the `PublicMint` and `TokenSeed` actors of the published `KCC20PublicMint`
//!   app, and the genesis check of its tokens.
//! - [`kusdt`]: kUSDT, a federated-bridge token of that app. It has a pinned `BridgeMint`
//!   companion, burn owners and redemption payloads.
//!
//! # Checks and support
//!
//! - [`verify`]: validation through the rusty-kaspa v2.1.0 script engine (feature `engine`).
//! - [`vectors`]: the golden-vector file format.
//! - [`redact`]: node and indexer URLs as they may be logged or shown, without credentials or
//!   API keys.

