#!/usr/bin/env node
// Generates web/src/kob/programs.generated.ts from the token-program profile table of kob-protocol
// (crates/kob-protocol/data/programs.json): the single declaration of every token program. Adding a program to the JSON and re-running
// `npm run gen:programs` is all the web app needs. A vitest (programs.generated.test.ts) fails when the committed file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const SOURCE_URL = new URL('../../crates/kob-protocol/data/programs.json', import.meta.url);
export const OUTPUT_URL = new URL('../src/kob/programs.generated.ts', import.meta.url);

const HEADER = '// @generated by web/scripts/gen-programs.mjs from crates/kob-protocol/data/programs.json. Do not edit.';
const CODECS = ['kcc20', 'kron'];

const q = (s) => `'${String(s).replace(/[\\']/g, '\\$&')}'`;
const u64 = (v, what) => {
  if (!Number.isSafeInteger(v) || v < 0) throw new Error(`${what}: expected a non-negative safe integer, got ${String(v)}`);
  return q(String(v));
};
const int = (v, what) => {
  if (!Number.isInteger(v) || v < 0) throw new Error(`${what}: expected a non-negative integer, got ${String(v)}`);
  return String(v);
};

/** Renders the generated module from the parsed programs.json. */
export function render(json) {
  if (!json || !Array.isArray(json.programs) || json.programs.length === 0) throw new Error('programs.json: `programs` must be a non-empty array');
  const names = new Set();
  const ids = new Set();
  const entries = json.programs.map((p) => {
    const w = `program ${p?.name}`;
    if (typeof p.name !== 'string' || !/^[A-Za-z0-9_]+$/.test(p.name)) throw new Error(`${w}: bad name`);
    if (names.has(p.name)) throw new Error(`${w}: duplicate name`);
    names.add(p.name);
    if (typeof p.registry_id !== 'string' || !p.registry_id) throw new Error(`${w}: bad registry_id`);
    if (ids.has(p.registry_id)) throw new Error(`${w}: duplicate registry_id`);
    ids.add(p.registry_id);
    if (!CODECS.includes(p.codec)) throw new Error(`${w}: unknown codec ${String(p.codec)}`);
    const networks = p.networks ?? [];
    if (!Array.isArray(networks) || !networks.every((n) => typeof n === 'string' && /^[a-z0-9-]+$/.test(n))) throw new Error(`${w}: networks must be an array of network ids`);
    const trailing = p.witness?.trailing_pushes ?? [];
    if (!Array.isArray(trailing)) throw new Error(`${w}: witness.trailing_pushes must be an array`);
    const dd = p.default_decimals ?? null;
    if (dd !== null && (!Number.isInteger(dd.decimals) || dd.decimals < 0 || dd.decimals > 9 || typeof dd.source !== 'string' || !dd.source.trim())) {
      throw new Error(`${w}: default_decimals must be {decimals 0..=9, source}`);
    }
    return [
      '  {',
      `    name: ${q(p.name)},`,
      `    registryId: ${q(p.registry_id)},`,
      `    codec: ${q(p.codec)},`,
      `    templateHash: ${q(p.template_hash)},`,
      `    prefixLen: ${int(p.layout.prefix_len, `${w} prefix_len`)},`,
      `    stateLen: ${int(p.layout.state_len, `${w} state_len`)},`,
      `    suffixLen: ${int(p.layout.suffix_len, `${w} suffix_len`)},`,
      `    maxTokenInputs: ${int(p.slots.inputs, `${w} slots.inputs`)},`,
      `    maxTokenOutputs: ${int(p.slots.outputs, `${w} slots.outputs`)},`,
      `    custodyOwner: ${int(p.owners.custody, `${w} owners.custody`)},`,
      `    holderOwner: ${int(p.owners.holder, `${w} owners.holder`)},`,
      `    carrierFloor: ${u64(p.carrier_floor, `${w} carrier_floor`)},`,
      `    witnessScheme: ${q(p.witness.scheme)},`,
      `    trailingPushes: [${trailing.map(q).join(', ')}],`,
      `    routerIntents: ${p.router_intents === true ? 'true' : 'false'},`,
      `    review: ${q(p.review.status)},`,
      `    networks: [${networks.map(q).join(', ')}],`,
      `    defaultDecimals: ${dd === null ? 'null' : `{ decimals: ${dd.decimals}, source: ${q(dd.source)} }`},`,
      '  },',
    ].join('\n');
  });
  return `${HEADER}

/** Every token program kob-protocol embeds, in declaration order. \`carrierFloor\` is a U64 decimal string (sompi). */
export const TOKEN_PROGRAMS = [
${entries.join('\n')}
] as const;

type Row = (typeof TOKEN_PROGRAMS)[number];

export type TokenProgram = Row['name'];
export type Kcc20Program = Extract<Row, { codec: 'kcc20' }>['name'];
export type KronProgram = Extract<Row, { codec: 'kron' }>['name'];
export type ProgramProfile = Row;

/** Registry template id -> token program name. */
export const PROGRAM_OF_REGISTRY_ID: Readonly<Record<string, TokenProgram>> = Object.fromEntries(TOKEN_PROGRAMS.map((p) => [p.registryId, p.name]));

/** Token program name -> codec (\`kcc20\` 112-byte state, \`kron\` 46-byte state). */
export const CODEC_OF_PROGRAM: Readonly<Record<TokenProgram, 'kcc20' | 'kron'>> = Object.fromEntries(TOKEN_PROGRAMS.map((p) => [p.name, p.codec])) as Record<TokenProgram, 'kcc20' | 'kron'>;

export function isTokenProgram(name: string): name is TokenProgram {
  return Object.hasOwn(CODEC_OF_PROGRAM, name);
}

/**
 * The decimals a program's tokens are shown and traded with when a token declares none (its profile's \`default_decimals\`: a launchpad's
 * convention, KaspaRocket 3), with the source the apps name for them; null: the program has none.
 */
export function programDefaultDecimals(name: string | null | undefined): { decimals: number; source: string } | null {
  const p = TOKEN_PROGRAMS.find((x) => x.name === name);
  return p?.defaultDecimals ?? null;
}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = render(JSON.parse(readFileSync(SOURCE_URL, 'utf8')));
  writeFileSync(OUTPUT_URL, out);
  console.log(`wrote ${fileURLToPath(OUTPUT_URL)}`);
}
