#!/usr/bin/env node
// Generates web/src/kob/programs.generated.ts from crates/kob-protocol/data/programs.json, the
// token-program profile table of kob-protocol and the one declaration of every token program.
// To add a program, add it to the JSON and run `npm run gen:programs`. The vitest
// programs.generated.test.ts fails when the committed file is stale.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const SOURCE_URL = new URL('../../crates/kob-protocol/data/programs.json', import.meta.url);
export const OUTPUT_URL = new URL('../src/kob/programs.generated.ts', import.meta.url);
/**
 * The top-up extra of each token program, in sompi, see bid-delivery-spec §9. It is the relay-fee
 * difference at the floor rate between a top-up fill and a new-delivery fill of the same order.
 * kob-protocol generates it with the final templates.
 */
export const TOPUP_EXTRA_URL = new URL('../../crates/kob-protocol/data/topup_extra.json', import.meta.url);
/**
 * The reference values that bid-delivery-spec §9 records from the prototype, used until
 * topup_extra.json exists. A program without a value has no top-up default, and the wallet does not
 * offer top-up for it.
 */
export const TOPUP_EXTRA_REFERENCE = { KCC20Ref: 595400, KCC20PublicMint: 818600, KForgeToken7214: 1455200, KaspaRocketToken11458: 2304000 };

/**
 * Reads topup_extra.json, either `{ name: sompi }` or `{ programs: { name: sompi } }`. Returns null
 * when the file does not exist.
 */
export function readTopupExtra() {
  if (!existsSync(TOPUP_EXTRA_URL)) return null;
  const j = JSON.parse(readFileSync(TOPUP_EXTRA_URL, 'utf8'));
  return j && typeof j === 'object' && j.programs && typeof j.programs === 'object' ? j.programs : j;
}

const HEADER = '// @generated by web/scripts/gen-programs.mjs from\n// crates/kob-protocol/data/programs.json. Do not edit.';
const CODECS = ['kcc20', 'kron'];

const q = (s) => `'${String(s).replace(/[\\']/g, '\\$&')}'`;
const u64 = (v, what) => {
  if (!Number.isSafeInteger(v) || v < 0) throw new Error(`${what}: expected a non-negative safe integer, got ${String(v)}`);
  return q(String(v));
};
const int = (v, what) => {
  if (!Number.isInteger(v) || v < 0) throw new Error(`${what}: expected a non-negative integer, got ${String(v)}`);
  return String(v);
};

/** Renders the generated module from the parsed programs.json. */
export function render(json, topupExtra = null) {
  if (!json || !Array.isArray(json.programs) || json.programs.length === 0) throw new Error('programs.json: `programs` must be a non-empty array');
  const extras = topupExtra ?? TOPUP_EXTRA_REFERENCE;
  const extraSource = topupExtra ? 'crates/kob-protocol/data/topup_extra.json' : 'the reference values of bid-delivery-spec §9, until topup_extra.json exists';
  for (const n of Object.keys(extras)) {
    const p = json.programs.find((x) => x?.name === n);
    if (!p) throw new Error(`topup extra: unknown program ${n}`);
    if (p.codec !== 'kcc20' && extras[n] !== null) throw new Error(`topup extra: ${n} is not a KCC-20 program (a KRON delivery is mode 0)`);
  }
  const names = new Set();
  const ids = new Set();
  const entries = json.programs.map((p) => {
    const w = `program ${p?.name}`;
    if (typeof p.name !== 'string' || !/^[A-Za-z0-9_]+$/.test(p.name)) throw new Error(`${w}: bad name`);
    if (names.has(p.name)) throw new Error(`${w}: duplicate name`);
    names.add(p.name);
    if (typeof p.registry_id !== 'string' || !p.registry_id) throw new Error(`${w}: bad registry_id`);
    if (ids.has(p.registry_id)) throw new Error(`${w}: duplicate registry_id`);
    ids.add(p.registry_id);
    if (!CODECS.includes(p.codec)) throw new Error(`${w}: unknown codec ${String(p.codec)}`);
    const networks = p.networks ?? [];
    if (!Array.isArray(networks) || !networks.every((n) => typeof n === 'string' && /^[a-z0-9-]+$/.test(n))) throw new Error(`${w}: networks must be an array of network ids`);
    const trailing = p.witness?.trailing_pushes ?? [];
    if (!Array.isArray(trailing)) throw new Error(`${w}: witness.trailing_pushes must be an array`);
    const dd = p.default_decimals ?? null;
    if (dd !== null && (!Number.isInteger(dd.decimals) || dd.decimals < 0 || dd.decimals > 9 || typeof dd.source !== 'string' || !dd.source.trim())) {
      throw new Error(`${w}: default_decimals must be {decimals 0..=9, source}`);
    }
    return [
      '  {',
      `    name: ${q(p.name)},`,
      `    registryId: ${q(p.registry_id)},`,
      `    codec: ${q(p.codec)},`,
      `    templateHash: ${q(p.template_hash)},`,
      `    prefixLen: ${int(p.layout.prefix_len, `${w} prefix_len`)},`,
      `    stateLen: ${int(p.layout.state_len, `${w} state_len`)},`,
      `    suffixLen: ${int(p.layout.suffix_len, `${w} suffix_len`)},`,
      `    maxTokenInputs: ${int(p.slots.inputs, `${w} slots.inputs`)},`,
      `    maxTokenOutputs: ${int(p.slots.outputs, `${w} slots.outputs`)},`,
      `    custodyOwner: ${int(p.owners.custody, `${w} owners.custody`)},`,
      `    holderOwner: ${int(p.owners.holder, `${w} owners.holder`)},`,
      `    carrierFloor: ${u64(p.carrier_floor, `${w} carrier_floor`)},`,
      `    witnessScheme: ${q(p.witness.scheme)},`,
      `    trailingPushes: [${trailing.map(q).join(', ')}],`,
      `    routerIntents: ${p.router_intents === true ? 'true' : 'false'},`,
      `    review: ${q(p.review.status)},`,
      `    networks: [${networks.map(q).join(', ')}],`,
      `    defaultDecimals: ${dd === null ? 'null' : `{ decimals: ${dd.decimals}, source: ${q(dd.source)} }`},`,
      `    topupExtra: ${extras[p.name] === undefined || extras[p.name] === null ? 'null' : u64(Number(extras[p.name]), `${w} topup extra`)},`,
      '  },',
    ].join('\n');
  });
  return `${HEADER}

/**
 * Every token program kob-protocol embeds, in declaration order.
 *
 * \`carrierFloor\` is in sompi, as a U64 decimal string. \`topupExtra\` is the extra relay fee of a
 * top-up fill, see bid-delivery-spec §9. It is in sompi, as a U64 decimal string, or null when the
 * program has no top-up. The values come from
 * ${extraSource}.
 */
export const TOKEN_PROGRAMS = [
${entries.join('\n')}
] as const;

type Row = (typeof TOKEN_PROGRAMS)[number];

export type TokenProgram = Row['name'];
export type Kcc20Program = Extract<Row, { codec: 'kcc20' }>['name'];
export type KronProgram = Extract<Row, { codec: 'kron' }>['name'];
export type ProgramProfile = Row;

/** Registry template id -> token program name. */
export const PROGRAM_OF_REGISTRY_ID: Readonly<Record<string, TokenProgram>> = Object.fromEntries(TOKEN_PROGRAMS.map((p) => [p.registryId, p.name]));

/** Token program name -> codec. A \`kcc20\` state is 112 bytes and a \`kron\` state 46 bytes. */
export const CODEC_OF_PROGRAM: Readonly<Record<TokenProgram, 'kcc20' | 'kron'>> = Object.fromEntries(TOKEN_PROGRAMS.map((p) => [p.name, p.codec])) as Record<TokenProgram, 'kcc20' | 'kron'>;

/** Whether \`name\` is a token program of this table. */
export function isTokenProgram(name: string): name is TokenProgram {
  return Object.hasOwn(CODEC_OF_PROGRAM, name);
}

/**
 * The decimals of a program's tokens when a token declares none, with the source the apps name for
 * them, or null when the program has none. They are the profile's \`default_decimals\`, a
 * launchpad's convention such as KaspaRocket's 3.
 */
export function programDefaultDecimals(name: string | null | undefined): { decimals: number; source: string } | null {
  const p = TOKEN_PROGRAMS.find((x) => x.name === name);
  return p?.defaultDecimals ?? null;
}

/**
 * The top-up extra of a program in sompi, see bid-delivery-spec §9. It is null for a KRON program
 * and for one not measured.
 */
export function programTopupExtra(name: string | null | undefined): bigint | null {
  const p = TOKEN_PROGRAMS.find((x) => x.name === name);
  return p?.topupExtra == null ? null : BigInt(p.topupExtra);
}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = render(JSON.parse(readFileSync(SOURCE_URL, 'utf8')), readTopupExtra());
  writeFileSync(OUTPUT_URL, out);
  console.log(`wrote ${fileURLToPath(OUTPUT_URL)}`);
}
