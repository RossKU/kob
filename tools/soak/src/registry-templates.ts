const ZERO32 = '0'.repeat(64);

export function externalRegistryToken(t: ExternalTokenConfig): Record<string, unknown> {
  if (!/^[0-9a-f]{64}$/.test(t.covenantId)) throw new Error(`externalTokens ${t.ticker}: covenantId must be 64 lowercase hex characters`);
  const tpl = t.program === 'KCC20PublicMint' ? TEMPLATE_PUBLIC_MINT : TEMPLATE_STANDARD;
  return {
    ticker: t.ticker,
    name: t.name,
    family: 'kcc20',
    covenant_id: t.covenantId,
    template_id: tpl.id,
    extension_commitment: t.extensionCommitment ?? ZERO32,
    extension_class: 'fixed-supply-standard',
    decimals: t.decimals,
    max_token_inputs: tpl.max_token_inputs,
    max_token_outputs: tpl.max_token_outputs,
    status: 'listed',
    verified: true,
    display: { description: t.description ?? `${t.ticker}: a token issued outside the soak (${tpl.id}).` },
  };
}

/** The registry's templates: the standard program, plus the public-mint build when an external token uses it. */
export function soakTemplates(external: readonly ExternalTokenConfig[]): unknown[] {
  return external.some((t) => t.program === 'KCC20PublicMint') ? [TEMPLATE_STANDARD, TEMPLATE_PUBLIC_MINT] : [TEMPLATE_STANDARD];
}
