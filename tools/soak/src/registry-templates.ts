/** the templates of config `testPrograms`, by program name */
export const TEST_PROGRAM_TEMPLATES = { KForgeToken1785: TEMPLATE_KFORGE_1785, KaspaRocketToken11458: TEMPLATE_KASPAROCKET_11458 } as const;
export type TestProgram = keyof typeof TEST_PROGRAM_TEMPLATES;

const ZERO32 = '0'.repeat(64);

/** the registry template of an external token's program */
export function templateOf(program: ExternalTokenConfig['program']) {
  switch (program) {
    case 'KCC20PublicMint':
      return TEMPLATE_PUBLIC_MINT;
    case 'KronToken2433':
      return TEMPLATE_KRON_2433;
    case 'KronToken2732':
      return TEMPLATE_KRON_2732;
    case 'KForgeToken1785':
      return TEMPLATE_KFORGE_1785;
    case 'KaspaRocketToken11458':
      return TEMPLATE_KASPAROCKET_11458;
    default:
      return TEMPLATE_STANDARD;
  }
}

export function externalRegistryToken(t: ExternalTokenConfig): Record<string, unknown> {
  if (!/^[0-9a-f]{64}$/.test(t.covenantId)) throw new Error(`externalTokens ${t.ticker}: covenantId must be 64 lowercase hex characters`);
  const tpl = templateOf(t.program);
  const kron = tpl.family === 'kron';
  if (kron && t.extensionCommitment && t.extensionCommitment !== ZERO32) throw new Error(`externalTokens ${t.ticker}: a KRON token has no extension commitment`);
  return {
    ticker: t.ticker,
    name: t.name,
    family: tpl.family,
    covenant_id: t.covenantId,
    template_id: tpl.id,
    // KRON: no extension commitment, class `none` (registry rules); KCC-20: the token's commitment (all zero by default)
    extension_commitment: kron ? null : (t.extensionCommitment ?? ZERO32),
    extension_class: kron ? 'none' : 'fixed-supply-standard',
    decimals: t.decimals,
    max_token_inputs: tpl.max_token_inputs,
    max_token_outputs: tpl.max_token_outputs,
    status: 'listed',
    verified: true,
    display: { description: t.description ?? `${t.ticker}: a token issued outside the soak (${tpl.id}).` },
  };
}

/**
 * The registry's templates: the standard program, plus the public-mint build, the KRON programs and the launchpad test programs the
 * external tokens use or `testPrograms` names (in that order).
 */
export function soakTemplates(external: readonly ExternalTokenConfig[], testPrograms: readonly string[] = []): unknown[] {
  for (const p of testPrograms) if (!(p in TEST_PROGRAM_TEMPLATES)) throw new Error(`testPrograms: unknown program ${p}`);
  const out: { id: string }[] = [TEMPLATE_STANDARD];
  for (const tpl of [TEMPLATE_PUBLIC_MINT, TEMPLATE_KRON_2433, TEMPLATE_KRON_2732, TEMPLATE_KFORGE_1785, TEMPLATE_KASPAROCKET_11458]) {
    const named = testPrograms.some((p) => TEST_PROGRAM_TEMPLATES[p as TestProgram] === tpl);
    if (named || external.some((t) => templateOf(t.program) === tpl)) out.push(tpl);
  }
  return out;
}
